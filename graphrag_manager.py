"""Per-paper Microsoft GraphRAG lifecycle: scaffold, build, status, engine cache.

Each paper gets its own GraphRAG root at ``data/<paper_id>/graphrag/``. This module:
  * scaffolds the root (settings.yaml generated from this app's config + GraphRAG
    prompts copied from the bundled graphrag_template/),
  * dumps the corpus from paper.json,
  * builds the index in-process (blocking) or in a background thread,
  * tracks a small status.json the UI can poll (idle|building|ready|failed),
  * lazily constructs and caches one GraphRAGQA engine per paper.

Builds are heavy (minutes, many LLM calls). serve.py kicks one off in the background
when a paper without a healthy index becomes current; whole-paper chat degrades to the
old vector RAG until the index is ready.
"""
from __future__ import annotations

import json
import sys
import threading
import time
from pathlib import Path
from typing import Any

import config

# Parquets that must all exist for an index to count as "built".
_REQUIRED = ("entities", "communities", "community_reports", "text_units", "relationships")

# state machine: idle -> building -> ready | failed
_STATUS_FILE = "status.json"

# Per-paper engine cache + per-paper build lock (so we never build the same root twice).
_engines: dict[str, Any] = {}
_locks: dict[str, threading.Lock] = {}
_locks_guard = threading.Lock()


# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------

def root_for(paper_id: str) -> Path:
    return config.DATA_DIR / paper_id / "graphrag"


def _lock_for(paper_id: str) -> threading.Lock:
    with _locks_guard:
        return _locks.setdefault(paper_id, threading.Lock())


# ---------------------------------------------------------------------------
# Status
# ---------------------------------------------------------------------------

def _write_status(root: Path, state: str, message: str = "") -> None:
    root.mkdir(parents=True, exist_ok=True)
    (root / _STATUS_FILE).write_text(
        json.dumps({"state": state, "message": message, "updated_at": time.time()}),
        encoding="utf-8",
    )


def read_status(paper_id: str) -> dict[str, Any]:
    """UI-facing status. A live build wins; otherwise reconcile with parquet health."""
    root = root_for(paper_id)
    # An in-progress (possibly forced) rebuild takes precedence over stale parquets.
    if _lock_for(paper_id).locked():
        return {"state": "building", "message": "Rebuilding…"}
    if health(paper_id):
        return {"state": "ready", "message": ""}
    f = root / _STATUS_FILE
    if f.exists():
        try:
            return json.loads(f.read_text(encoding="utf-8"))
        except Exception:  # noqa: BLE001
            pass
    return {"state": "idle", "message": ""}


def health(paper_id: str) -> bool:
    """True if all required index output parquets exist."""
    out = root_for(paper_id) / "output"
    return all((out / f"{n}.parquet").exists() for n in _REQUIRED)


