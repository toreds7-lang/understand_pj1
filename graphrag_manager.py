def _corpus_text(paper: dict[str, Any]) -> str:
    """Concatenate page markdown into one corpus document, with light page markers."""
    parts: list[str] = []
    for p in paper.get("pages", []) or []:
        md = (p.get("markdown") or "").strip()
        if md:
            parts.append(f"[page {p.get('index', 0) + 1}]\n{md}")
    return "\n\n".join(parts)


def ensure_root(paper_id: str, paper: dict[str, Any]) -> Path:
    """Create/refresh the per-paper GraphRAG root: settings.yaml, prompts/, input corpus."""
    root = root_for(paper_id)
    (root / "input").mkdir(parents=True, exist_ok=True)
    (root / "prompts").mkdir(parents=True, exist_ok=True)

    (root / "settings.yaml").write_text(_settings_yaml(), encoding="utf-8")

    # Copy GraphRAG index/query prompts from the bundled template (only if missing,
    # so a user's local prompt tweaks survive a rebuild).
    tmpl = config.GRAPHRAG_TEMPLATE_DIR / "prompts"
    if tmpl.exists():
        for src in tmpl.glob("*.txt"):
            dst = root / "prompts" / src.name
            if not dst.exists():
                dst.write_text(src.read_text(encoding="utf-8"), encoding="utf-8")

    (root / "input" / f"{paper_id}.txt").write_text(_corpus_text(paper), encoding="utf-8")
    return root


# ---------------------------------------------------------------------------
# Build
# ---------------------------------------------------------------------------

def build(paper_id: str, paper: dict[str, Any]) -> None:
    """Scaffold + build the index in-process (blocking). Records status.json.

    Serialized per paper by a lock so a manual rebuild can't collide with the
    auto-build kicked off on paper load.
    """
    lock = _lock_for(paper_id)
    if not lock.acquire(blocking=False):
        print(f"[graphrag] build already in progress for {paper_id}", file=sys.stderr)
        return
    root = root_for(paper_id)
    try:
        _write_status(root, "building", "Scaffolding GraphRAG root…")
        ensure_root(paper_id, paper)
        _write_status(root, "building", "Building knowledge graph (entities, communities, reports)…")
        print(f"[graphrag] building index for {paper_id} …", file=sys.stderr)
        # Imported lazily so the heavy graphrag import only happens when we actually build.
        from graphrag_qa import build_index
        build_index(root)
        _engines.pop(paper_id, None)  # force re-load of the fresh index on next query
        _write_status(root, "ready", "")
        print(f"[graphrag] index ready for {paper_id}", file=sys.stderr)
    except Exception as e:  # noqa: BLE001 — surface a clear, recoverable failure
        _write_status(root, "failed", f"{type(e).__name__}: {e}")
        print(f"[graphrag] build FAILED for {paper_id}: {e}", file=sys.stderr)
    finally:
        lock.release()


def build_async(paper_id: str, paper: dict[str, Any], force: bool = False) -> bool:
    """Start a background build. Returns True if started.

    Auto-build (force=False) is skipped when an index already exists. A manual rebuild
    (force=True) proceeds even when healthy, but never collides with a running build.
    """
    if not force and health(paper_id):
        return False
    lock = _lock_for(paper_id)
    if lock.locked():
        return False
    t = threading.Thread(target=build, args=(paper_id, paper), daemon=True,
                         name=f"graphrag-build-{paper_id}")
    t.start()
    return True


# ---------------------------------------------------------------------------
# Engine
# ---------------------------------------------------------------------------

def get_engine(paper_id: str):
    """Return a cached GraphRAGQA engine for the paper, or None if not built yet."""
    if not health(paper_id):
        return None
    eng = _engines.get(paper_id)
    if eng is None:
        from graphrag_qa import GraphRAGQA
        eng = GraphRAGQA(root=root_for(paper_id))
        _engines[paper_id] = eng
    return eng
